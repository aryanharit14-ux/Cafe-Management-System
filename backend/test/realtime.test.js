const {test}=require('node:test');
const assert=require('node:assert/strict');
const {io:connect}=require('socket.io-client');
const {createServer}=require('node:http');
const {createApp}=require('../app');
const {attachRealtime}=require('../realtime');
const {testDatabase}=require('./database');
function event(socket,name){return new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Timed out waiting for '+name)),5000);socket.once(name,value=>{clearTimeout(timer);resolve(value);});});}
test('live updates reach owner and staff, isolate other users, refresh menus and revoke logout sessions',async t=>{
  const database=await testDatabase();
  const app=await createApp({database,adminEmail:'staff@live.example',adminPassword:'Live-staff-password',paymentConfig:{}});
  const server=createServer(app),io=attachRealtime(server,app);
  server.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const base=`http://127.0.0.1:${server.address().port}`;
  const sockets=[];
  t.after(async()=>{for(const s of sockets)s.disconnect();await new Promise(r=>io.close(r));await database.close();});
  const request=async(path,body,token,method=body?'POST':'GET')=>{const r=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()};};
  const owner=(await request('/auth/register',{name:'Owner',email:'owner@live.example',password:'Live-customer-password'})).data;
  const other=(await request('/auth/register',{name:'Other',email:'other@live.example',password:'Live-customer-password'})).data;
  const staff=(await request('/auth/login',{email:'staff@live.example',password:'Live-staff-password'})).data;
  const open=async token=>{const s=connect(base,{auth:{token},transports:['websocket'],forceNew:true,reconnection:false});sockets.push(s);await event(s,'connect');return s;};
  const a=await open(owner.token),b=await open(other.token),c=await open(staff.token),guest=await open();
  let leaks=0;b.on('orders:changed',()=>leaks++);guest.on('orders:changed',()=>leaks++);
  const ownerEvent=event(a,'orders:changed'),staffEvent=event(c,'orders:changed');
  const body={requestKey:'live-checkout-key',orderItems:[{menuItem:'latte',qty:1}],store:'Juniper • Central café',method:'Takeaway'};
  const results=await Promise.all([request('/orders',body,owner.token),request('/orders',body,owner.token)]);
  assert.deepEqual(results.map(r=>r.status).sort(),[200,201]);assert.equal(results[0].data._id,results[1].data._id);
  const id=results[0].data._id;
  assert.equal((await ownerEvent).orderId,id);assert.equal((await staffEvent).orderId,id);
  const changed=event(a,'orders:changed');
  const updates=await Promise.all([request('/orders/'+id+'/status',{status:'Preparing'},staff.token,'PUT'),request('/orders/'+id+'/status',{status:'Preparing'},staff.token,'PUT')]);
  assert.deepEqual(updates.map(r=>r.status).sort(),[200,400]);assert.equal((await changed).status,'Preparing');
  const menuEvent=event(guest,'menu:changed');
  assert.equal((await request('/menu',{name:'Live brew',description:'Test',category:'Hot coffee',price:200,image:'/images/latte.jpg',isAvailable:true},staff.token)).status,201);
  await menuEvent;
  const disconnected=event(a,'disconnect');await request('/auth/logout',{},owner.token);await disconnected;
  const invalid=connect(base,{auth:{token:owner.token},reconnection:false});sockets.push(invalid);await event(invalid,'connect_error');
  await database.update('sessions',{token:other.token},{$set:{expires:Date.now()-1}});
  const expired=connect(base,{auth:{token:other.token},reconnection:false});sockets.push(expired);await event(expired,'connect_error');
  assert.equal(leaks,0);assert.equal(await database.count('orders'),1);
});
